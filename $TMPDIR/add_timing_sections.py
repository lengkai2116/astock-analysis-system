count = 0
errors = []
for m in modules:
    fpath = os.path.join(BASE, m["file"])
    try:
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()
        if m["anchor"] not in content:
            errors.append(f"{m['file']}: anchor not found")
            continue
        new_content = content.replace(m["anchor"], m["anchor"] + m["insert"])
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(new_content)
        count += 1
        print(f"✅ {m['file']}")
    except Exception as e:
        errors.append(f"{m['file']}: {e}")

print(f"\n=== Done: {count}/14 updated ===")
